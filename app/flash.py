from fastapi import Request

# Сколько символов сообщения переживает дорогу до страницы.
#
# Флеш едет в cookie сессии: подписанный JSON в base64. Кириллица в UTF-8 —
# два байта на символ, base64 добавляет ещё треть, плюс подпись. Браузеры
# отбрасывают cookie длиннее 4096 байт ЦЕЛИКОМ и молча — не обрезают, а
# выбрасывают вместе с сессией.
#
# Замер 21.09: импорт двенадцати строк с ошибками дал cookie в 7106 байт. То
# есть оператор, загрузивший файл с ошибками, видел страницу вообще без
# сообщения — ни сколько строк применилось, ни сколько не применилось и почему.
# Причём чем хуже прошёл импорт, тем вернее пропадало сообщение: длина растёт
# вместе с числом и длиной ошибок.
#
# Цифра посчитана, а не прикинута, и она меньше, чем кажется разумным. JSON
# сессии кодируется с экранированием не-ASCII, поэтому КАЖДАЯ кириллическая
# буква занимает шесть байт (`\uXXXX`), а после base64 — 8,76 байта. При запасе
# в 200 байт на подпись, логин, имя cookie и атрибуты остаётся 444 символа.
# Первая попытка поставить предел в тысячу символов дала cookie в 6674 байта —
# то есть сообщение пропало бы ровно так же, как и без предела.
MAX_FLASH_CHARS = 440

TRUNCATION_NOTE = "… (сообщение длинное, показано начало)"


def set_flash(request: Request, message: str, kind: str = "info"):
    """Положить сообщение до следующей страницы.

    Длинное сообщение ОБРЕЗАЕТСЯ, а не выбрасывается: начало важнее конца —
    там итоги («обновлено N, ошибок M»), а в конце примеры ошибок. Потерять
    примеры неприятно, потерять всё сообщение — значит оставить человека в
    уверенности, что файл применился целиком.
    """
    if len(message) > MAX_FLASH_CHARS:
        keep = MAX_FLASH_CHARS - len(TRUNCATION_NOTE)
        message = message[:keep].rstrip() + TRUNCATION_NOTE
    request.session["flash"] = {"message": message, "kind": kind}


def pop_flash(request: Request):
    return request.session.pop("flash", None)

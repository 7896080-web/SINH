"""Кто какие страницы видит. **ЗАПРЕТ ПО УМОЛЧАНИЮ.**

Зачем роли вообще появились. Возвраты принимает кладовщик, и ему нужна ровно
одна страница. Всё остальное в этой админке он не просто «может случайно
нажать» — там кнопки, которые в один клик двигают боевые остатки: массовая
правка на «Товарах» (одно нажатие по отбору в 1739 строк), «Переотправить
остаток» на «Диагностике», токены площадок на «API-ключах», отправка на живую
площадку с «Тестирования», переподвязка баркодов на «Мэппинге». Это не вопрос
опрятности интерфейса, это граница безопасности.

**Разрешение перечисляется, запрет не перечисляется.** Роль склада получает
список разрешённых префиксов, всё прочее закрыто. Сделай наоборот — перечисли
запрещённое, — и КАЖДАЯ новая страница окажется открытой складу по умолчанию,
потому что автор новой страницы про этот список не вспомнит. Про него не
вспомнят и в этом варианте, но цена ошибки обратная: страница будет закрыта,
человек скажет «не открывается», и её откроют осознанно. Молчаливое открытие
доступа никто не заметит никогда.

**Проверка живёт в `get_current_user`, а не в каждом обработчике.** Забыть
дописать её в новый роутер нельзя: страница без этой зависимости не открывается
вовсе — она не знает, кто пришёл. То есть единственный способ «обойти» проверку
делает страницу недоступной всем, а не только складу.

Прятать пункт меню — НЕ защита, а вежливость: адрес можно набрать руками.
Меню фильтруется тем же списком (`templating` регистрирует `can_see`), чтобы
человек не видел того, чего ему всё равно не откроют, но стережёт доступ именно
отказ на входе в страницу.
"""

from __future__ import annotations

# Страницы складской учётной записи. ПРЕФИКСАМИ, а не точными адресами: у
# раздела есть фрагменты htmx, печать этикетки и выгрузка — все они начинаются
# с того же корня, и перечислять их поимённо значит однажды забыть один.
WAREHOUSE_ALLOWED = ("/returns",)

# Доступно без входа. `/health` — мониторинг (его же опрашивает сторож
# веб-службы), `/static` — стили и скрипты, без них страница входа не
# нарисуется.
PUBLIC = ("/login", "/logout", "/health", "/static")

# Куда попадает человек после входа и с корня. У склада это его единственная
# страница: отправь мы его на общий `/mapping`, он увидел бы отказ сразу после
# успешного входа и решил, что учётная запись не работает.
HOME = {"admin": "/mapping", "warehouse": "/returns"}


def _under(path: str, prefix: str) -> bool:
    """Путь внутри раздела. Ровно совпал или продолжился СЛЕШЕМ.

    Голый `startswith` открыл бы складу `/returns-secret` и любую будущую
    страницу, чьё имя начинается с тех же букв, — а такие заводят не думая.
    """
    return path == prefix or path.startswith(prefix + "/")


def is_public(path: str) -> bool:
    return any(_under(path, p) for p in PUBLIC)


def allowed(role: str, path: str) -> bool:
    """Можно ли этой роли открыть этот адрес."""
    if is_public(path):
        return True
    if role == "warehouse":
        return any(_under(path, p) for p in WAREHOUSE_ALLOWED)
    # Администратор — всё остальное. Новая роль, если появится, по умолчанию не
    # получит ничего: `allowed` вернёт False, и это правильный дефолт.
    return role == "admin"


def home_for(role: str) -> str:
    return HOME.get(role, "/mapping")

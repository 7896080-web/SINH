"""Единый источник текущего времени для всего приложения.

Заменяет устаревший ``datetime.utcnow()`` (помечен на удаление в будущих
версиях Python). Возвращает **naive** UTC-время — намеренно, без tzinfo:
все колонки ``DateTime`` в моделях naive, а смешивать naive и aware
``datetime`` нельзя — их сравнение бросает ``TypeError``. Так что семантика
ровно та же, что была у ``datetime.utcnow()``, просто без депрекации.
"""
from datetime import date, datetime, timezone


def now_utc() -> datetime:
    return datetime.now(timezone.utc).replace(tzinfo=None)


def today_local() -> date:
    """Сегодняшнее число ПО ЧАСАМ СЕРВЕРА, а не по UTC.

    Календарные даты, которые видит человек и которыми мы разговариваем с 1С
    («остатки на дату», «активно с»), живут в часовом поясе сервера: 1С стоит на
    той же машине, и её «сегодня» — это местное сегодня. У Москвы UTC+3, поэтому
    с 00:00 до 03:00 местное число уже на день больше UTC-шного, и проверка
    «дата не из будущего» по UTC в эти три часа отвергала СЕГОДНЯШНЮЮ дату со
    словами «остатков на будущую дату в 1С нет», а на странице «Остатки на дату»
    календарь ещё и упирался максимумом во вчера — заказать срез на сегодня было
    нельзя. Ровно на этом 19.09 в 00:10 МСК упал `test_a_future_date_is_refused`:
    `/testing` считал по местному, остальные страницы — по UTC, и завтрашнее для
    UTC число оказывалось сегодняшним для сервера.

    Отметки времени (`DateTime`-колонки) при этом остаются в UTC — см. `now_utc`.
    Разделение намеренное: момент времени хранится в UTC, календарный день,
    названный человеком, — местный.
    """
    return datetime.now().date()


def local_day_start_utc(day: date) -> datetime:
    """Момент, в который МЕСТНЫЙ календарный день начался, — в UTC (aware).

    Нужен там, где человеческую дату надо превратить в отметку времени для
    площадки. Соблазнительный короткий путь — ``datetime(y, m, d,
    tzinfo=timezone.utc)`` — даёт не начало дня, а 03:00 по Москве: заказы
    первых трёх часов суток остаются за границей запроса. Для базовой даты
    расчёта это значит, что их продажи не проведутся, остаток ЦС останется
    завышенным ровно на них, а «актуализирован» встанет, потому что площадка
    ответила без ошибки, — то есть трансляция уедет с завышенным числом.

    Наивное время ``astimezone`` трактует как местное — ровно то, что нужно:
    часовой пояс берётся у машины, как и у ``today_local``.
    """
    return datetime(day.year, day.month, day.day).astimezone(timezone.utc)


def local_date_of(moment: datetime) -> date:
    """Местное календарное число момента времени.

    Дата заказа площадки уезжает в 1С датой перемещения, а 1С живёт по местным
    часам. Взятая из UTC-времени, она у заказа, сделанного до трёх часов ночи,
    оказывается вчерашней — документ встаёт не тем днём, а при расчёте ещё и
    раньше базовой даты, на которую снят остаток.

    Наивный момент считаем UTC-шным: так хранятся все ``DateTime``-колонки.
    """
    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=timezone.utc)
    return moment.astimezone().date()

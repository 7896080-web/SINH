"""Аномалия, причина которой исчезла, не должна висеть в списке.

Аномалия — это запись о том, что заказ пришёл на товар, с которым мы работать
не могли: трансляция на этот кабинет не включена, или у товара нет баркода.
Пока причина держится, строка нужна. Но причину устраняют не только кнопкой
«Синхронизировать» на этой же странице: товар включают на «Товарах», массовой
правкой, импортом из Excel, баркод приезжает справочником из 1С. Во всех этих
случаях аномалия оставалась в списке навсегда — и список рос, хотя разбирать в
нём было нечего.

20.09 на бою их накопилось 93, почти все — «заказ на невключённый товар» по
каталогу, который ещё ведёт вторая система. Список, который не пустеет от
работы, перестают открывать: в нём не видно, сделано что-то или нет.

Гасим ровно то, чего больше нет:
  * «заказ на невключённый товар» — пара товар+кабинет включена;
  * «нет баркода при включённой галочке» — у товара появился баркод.

Остальное трогать нельзя: закрытая аномалия исчезает из работы, и закрыть её
по ошибке значит потерять заказ, который никто не разнёс.
"""

from sqlalchemy.orm import Session

from app.models import (AnomalyReason, AnomalyStatus, Barcode, SyncAnomaly,
                        SyncSetting)


def close_fixed_anomalies(db: Session) -> int:
    """Закрыть аномалии, причина которых устранена. Возвращает сколько закрыто.

    Коммит НЕ делает: вызывающий сам решает, когда фиксировать — страница
    аномалий делает это одной транзакцией со своим ответом.

    Двумя массовыми `UPDATE`, а не перебором строк в Python, и это не про
    скорость. Прежний вид грузил ВСЕ открытые аномалии целыми объектами и строил
    `IN` по всем их товарам — то есть на 32 766 разных товарах SQLite ответил бы
    «too many SQL variables», и страница аномалий перестала бы открываться
    ВОВСЕ. А она единственное место, где их разбирают. Предел параметров в этом
    проекте уже знают (`products.UIDS_CHUNK` — про 999 у сборок до 3.32, чего на
    машине разработки не увидеть), здесь он просто не был применён.

    Срок, за который это наступит, считается по данным, а не по страху: строки
    в статусе `new` не чистит НИКТО намеренно — аномалия в `new` это
    незаконченное дело, и `retention` её не трогает, сколько бы ей ни было. Пока
    идёт переход со старой системы, «заказ на невключённый товар» приходит
    десятками в сутки и сам не закрывается: пару товар+кабинет никто не включит,
    потому что этим каталогом мы ещё не управляем. Сотня в сутки — это год,
    триста — четыре месяца. И страница обновляет себя каждые две минуты, то есть
    запрос этот не редкий.

    `synchronize_session="fetch"` обязателен. Прежний код менял ORM-объекты, и
    вызывающие читают состояние СРАЗУ, не коммитя (так же и тесты): с `False`
    они увидели бы в сессии прежний статус, то есть правка выглядела бы
    несработавшей ровно там, где её проверяют.
    """
    base = ((SyncAnomaly.status == AnomalyStatus.new)
            & SyncAnomaly.is_test.is_(False))

    # Пары «причина -> чем она лечится». Условие ОДНО и на вопрос «есть ли что
    # закрывать», и на само закрытие: спроси мы разным, проба однажды сказала
    # бы «нечего» там, где закрыть надо, — и строка висела бы вечно.
    #
    # «Заказ на невключённый товар» — пара товар+кабинет включена. Здесь
    # коррелированный EXISTS уместен: у `sync_settings` есть уникальный индекс
    # по паре (`uq_product_account`), то есть это индексный поиск, а не чтение
    # таблицы на каждую строку.
    #
    # «Нет баркода» — у товара появился баркод. А здесь, наоборот, `IN
    # (подзапрос)`: он не зависит от строки, и SQLite считает его ОДИН раз, а не
    # на каждую. Тем же правилом лечили поиск на «Товарах».
    cured = (
        (AnomalyReason.order_on_disabled,
         db.query(SyncSetting).filter(
             SyncSetting.uid_1c == SyncAnomaly.uid_1c,
             SyncSetting.account_id == SyncAnomaly.account_id,
             SyncSetting.enabled.is_(True),
         ).exists()),
        (AnomalyReason.missing_barcode,
         SyncAnomaly.uid_1c.in_(db.query(Barcode.uid_1c).scalar_subquery())),
    )

    closed = 0
    for reason, fixed in cured:
        criteria = (base, SyncAnomaly.reason == reason, fixed)
        # СНАЧАЛА спрашиваем чтением, есть ли что закрывать. Пустой `UPDATE` в
        # SQLite — это всё равно ПИСЬМО: он открывает транзакцию записи и берёт
        # блокировку ещё до того, как выяснится, что подходящих строк нет
        # (проверено: второй писатель в этот момент получает `database is
        # locked`). А `_render` коммитит только когда что-то закрылось, то есть
        # блокировка жила бы до конца запроса — на КАЖДОЙ загрузке страницы и
        # каждом её автообновлении раз в две минуты, пока в ту же базу пишут
        # рассылка (раз в 45 секунд) и приём заказов. Обычный случай здесь —
        # «закрывать нечего», и он обязан быть чтением.
        if db.query(SyncAnomaly.id).filter(*criteria).limit(1).first() is None:
            continue
        closed += db.query(SyncAnomaly).filter(*criteria).update(
            {"status": AnomalyStatus.resolved}, synchronize_session="fetch")

    return closed

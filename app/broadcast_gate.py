"""Ворота трансляции: сначала расчёт, потом отправка наружу.

Жило в роутере «Товаров» и спрашивалось только оттуда, пока включение делал
человек руками. Теперь тот же вопрос задаёт расчёт — строке, которую попросили
включить файлом Excel и которая ждала окончания расчёта. Условие обязано быть
ОДНО на оба пути: разойдись они, отложенное включение открыло бы трансляцию там,
где страница её включать не даёт, и на площадки уехал бы остаток, не сверенный
с их продажами.
"""

from app.models import Product
from app.transmit import covered_accounts


def calc_status(product: Product, has_cabinet: bool = True,
                 enabled_ids: set[int] | None = None) -> tuple[str, str]:
    """Состояние расчёта строки: (код, подпись для оператора).

    Отвечает на единственный вопрос, который у оператора возникает на каталоге в
    152 тысячи SKU: «эту строку я уже обработал или нет?». По цифрам в ячейке это
    не понять — пустой факт выглядит одинаково и когда его не вводили, и когда
    решили, что учёт 1С верен.

    `ready` означает всё сразу: порог посчитан и подтверждён, отгрузки площадок
    за период проведены в 1С, остаток ЦС актуален — товар можно включать в
    трансляцию. Раньше этим словом назывался только посчитанный порог, но это
    разные состояния, и путать их нельзя: с непроведёнными отгрузками остаток
    завышен, и включённая трансляция отправит на площадки лишнее.
    """
    if not has_cabinet:
        # Ни одного отмеченного кабинета: заказы спрашивать негде и транслировать
        # некуда. Без этой подписи оператор видел «нужен расчёт», запускал его и
        # получал молчаливый пустой проход — задание отчитывалось «0 заказов», а
        # причина оставалась только в строке задания, которой на странице нет.
        return ("no_cabinet", "не выбран кабинет")
    if product.offset_base_date is None:
        return ("none", "расчёт не начат")
    if product.offset_base_stock is None:
        return ("waiting", "ждём 1С")
    if product.fact_at_date is None and product.stock_discrepancy is None:
        # Порог уже считается (сводится к брони), но человек цифру не подтвердил.
        # Пока не подтвердил — строка не «обработана».
        #
        # Хранимое расхождение — ТА САМАЯ подтверждённая цифра, только снятая на
        # другую дату: склад пересчитали, разницу с учётом записали, и она не
        # зависит от того, какое число стоит в поле даты. Спрашивай мы здесь один
        # факт, каждый сдвиг даты назад (а его делают, чтобы догнать заказы за
        # более ранний период) возвращал бы строку в «нужен факт» и ЗАКРЫВАЛ
        # ворота трансляции по товару, у которого с порогом всё в порядке. А
        # вписать факт на прошлое число оператору неоткуда — склад в прошлом не
        # пересчитать.
        return ("need_fact", "нужен факт")
    if product.recalc_done_at is None:
        # Порог посчитан, но отгрузки на маркетплейсы за период в 1С ещё не
        # проведены: остаток ЦС завышен, и включать трансляцию рано — уедет
        # число больше реального.
        return ("need_recalc", "нужен расчёт")
    # Расчёт был, но после него отметили ещё кабинет. По нему заказы не поднимали,
    # значит остаток не сверен именно с его продажами — «актуализирован» тут было
    # бы неправдой, а ровно на эту неправду оператор и опирается, включая
    # трансляцию. Транслировать в такой кабинет лестница не даёт (ступень 2).
    if enabled_ids and not enabled_ids.issubset(covered_accounts(product)):
        return ("need_recalc_account", "нужен пересчёт: добавлен кабинет")
    return ("ready", "актуализирован")


# Состояния, из которых строка выберется САМА, без человека: расчёт поднимет
# заказы, 1С ответит на заявку о дате. Просьбу «включить трансляцию» из файла
# Excel имеет смысл запоминать только по ним. Остальные без человека не
# исчезнут — не отмечен кабинет, не задана дата, не введён факт, — и молча
# запомненная просьба превратилась бы в обещание, которое никто не выполнит.
DEFERRABLE_CALC_STATUSES = frozenset({"waiting", "need_recalc", "need_recalc_account"})


def enabled_account_ids(product: Product) -> set[int]:
    """Кабинеты, отмеченные для товара И ЖИВЫЕ.

    Ворота сравнивают этот набор с тем, что покрыл расчёт, а расчёт опрашивает
    только активные кабинеты (`recalc._enabled_accounts`). Пока ворота брали ВСЕ
    отмеченные, кабинет, который сам себя выключил после пяти сбоёв подряд
    (`circuit_breaker` — осознанное поведение, не баг), навсегда запирал строку в
    состоянии «нужен пересчёт: добавлен кабинет»: расчёт его не опрашивает и в
    покрытые не кладёт, значит `issubset` ложно всегда. Повторный расчёт ничего
    не менял, подпись не называла виновника, а включить трансляцию было нельзя ни
    по этому товару, ни по любому другому, отмеченному для того же кабинета, —
    включая совершенно здоровые кабинеты того же товара. Отложенные просьбы из
    Excel висели вечно.

    Условие обязано совпадать с тем, по которому расчёт выбирает кабинеты, иначе
    оно разойдётся второй раз.
    """
    return {s.account_id for s in product.sync_settings
            if s.enabled and (s.account is None or s.account.is_active)}


def blocks_broadcast_on(product: Product) -> str | None:
    """Почему этот товар нельзя включать в трансляцию. None — можно.

    Правило заказчика с самого начала одно: сначала расчёт, потом трансляция.
    Ступень 2 лестницы закрывает случай «расчёт был, но кабинет отметили позже»,
    а случай «расчёта не было вовсе» оставался открытым: у такого товара
    `recalc_done_at` пуст, ступень не срабатывает, и включение отправляет на
    площадки остаток, не сверенный ни с чем. Именно так выглядела строка
    ZJYM269002 XL — «ждём 1С», а рядом «→ 21 после включения».

    Проверяем на ВКЛЮЧЕНИИ. Выключение не трогаем никогда: снять с трансляции
    должно быть можно в любой момент и без условий.
    """
    enabled_ids = enabled_account_ids(product)
    code, label = calc_status(product, bool(enabled_ids), enabled_ids)
    if code == "ready":
        return None
    return label


def apply_pending_broadcast(product: Product) -> bool:
    """Включить трансляцию, если её просили включить и ворота открылись.

    Просьба приезжает импортом Excel: оператор отмечает в файле дату расчёта,
    факт, кабинеты и «Трансляция = Да» одной строкой — так он и думает о работе,
    а расчёт после этого идёт минутами и заканчивается без него. Раньше такая
    строка просто попадала в ошибки импорта, и включать её приходилось вторым
    заходом через сутки — по каталогу в тысячи позиций это и есть работа на день.

    Само условие не ослаблено ни на грамм: включаем ровно то, что в эту минуту
    включила бы страница (`blocks_broadcast_on` вернул None). Расчёт, закончившийся
    проблемами, отметки не ставит — значит и ворота не откроются, и просьба
    останется висеть до следующего расчёта.
    """
    if product.broadcast_requested_at is None or product.broadcast_enabled:
        return False
    if blocks_broadcast_on(product) is not None:
        return False
    product.broadcast_enabled = True
    product.broadcast_requested_at = None
    return True


def drop_recalc_mark(product: Product) -> bool:
    """Снять «актуализирован»: набор баркодов товара изменился.

    Зовут это все, кто трогает привязку баркода. Расчёт собирает заказы строго
    по баркодам товара (`recalc.collect_orders`), поэтому его прошлый вывод к
    новому набору не относится: продажи по только что привязанному баркоду он
    заведомо не видел, и остаток завышен ровно на них.

    Пустая СТРОКА, а не NULL: покрытие аннулировано, но отслеживаем мы его
    по-прежнему. NULL означал бы «расчёта никогда не было», и ступень 2 лестницы
    перестала бы срабатывать вовсе — снятие отметки ОТКРЫВАЛО бы трансляцию
    несверенного остатка вместо того, чтобы закрыть её.

    И обратная предосторожность: у товара, где расчёта не было НИКОГДА
    (`recalc_done_at` пуст), не трогаем ничего. Выставить ему пустую строку
    значит включить ту самую ступень 2, которая для таких товаров обязана
    молчать, — на отмеченный кабинет уехал бы ноль. На этом уже спотыкались
    в `offset_base.set_base_date`, и поймал это тест, а не глаза.

    Возвращает True, если отметку действительно сняли, — вызывающему бывает
    нужно это посчитать.
    """
    if product is None or product.recalc_done_at is None:
        return False
    product.recalc_done_at = None
    product.recalc_account_ids = ""
    return True

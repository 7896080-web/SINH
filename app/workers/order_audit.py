"""Суточная сверка заказов с площадками: заказ у них есть, а у нас его нет.

Живой опрос (`order_poller.poll_new_orders`) спрашивает у площадки ОЧЕРЕДЬ
неподтверждённых заказов — у WB это `/api/v3/orders/new`. Заказ, вышедший из
этой очереди, живым опросом не виден больше НИКОГДА, сколько бы раз он ни
отработал. А выйти он может так:

* кабинет был погашен — предохранителем, паузой или руками: per-account
  задание снято, очередь не читается вовсе, а `/health` выключенные кабинеты
  пропускает намеренно;
* 429 или таймаут в тот цикл, а заказ тем временем подтвердили;
* заказ подтвердил кто-то в кабинете — человек или ВТОРАЯ система, та, с
  которой идёт переход;
* `process_new_order` упал на этой строке (`stats["failed"]`).

Следствие одно и дорогое: перемещение в 1С не создано, значит остаток ЦС
завышен ровно на этот заказ, и наружу уходит больше, чем есть. Само это не
исправится: следующего события по строке может не быть месяцами.

**Часовая сверка с 1С такой пропуск не ловит и не может — она его МАСКИРУЕТ.**
Она считает `ждали = наш остаток + «в пути»`, и у пропущенного заказа все
слагаемые невинны: наш остаток не уменьшен, «в пути» пусто, остаток 1С тот же
(документа-то нет). Разница ноль, строка `resolved`, отчёт молчит — обе
стороны согласованно врут на одну величину. Увидеть это можно было только
пересчётом склада руками либо «Расчётом» по кнопке: до 29.10 ленту заказов
целиком поднимал ОДИН `recalc.collect_orders`, то есть ровно тогда, когда
человек нажмёт.

Три решения, и каждое обязательно.

**Проводим, а не только называем.** Это выбор, и он сознательный: названная,
но не проведённая продажа оставляет остаток завышенным до того, как человек
дойдёт до списка, — а дорога ошибки здесь односторонняя, в сторону оверселла.
Проводим ТЕМ ЖЕ `process_new_order`, что живой опрос и расчёт: второй копии
логики приёма заказа в этом проекте нет и быть не должно.

**`respect_enabled=True` — то есть только по парам, где галочка кабинета
стоит.** Это главное ограничение, и без него механизм был бы катастрофой. Пока
идёт переход, часть каталога транслирует ещё старая система, и продажи по
неподключённым у нас карточкам идут мимо нас В ПОРЯДКЕ ВЕЩЕЙ: остаток по ним мы
не рассылали и не списывали. Проведи мы их — создали бы в 1С перемещения на
весь тридцатидневный поток чужих продаж, разом и без присмотра. Расчёт
(`catch_up_product`) ставит `respect_enabled=False` по обратной причине: там
товар выбрал ЧЕЛОВЕК и нажал кнопку. Отмеченная пара — ровно то множество, где
наш остаток уходит наружу, то есть где пропуск и есть оверселл.

**Отменённый на площадке заказ не проводим вовсе.** У живого опроса заказ жив
по построению; здесь — нет, в месячной ленте лежат и давно снятые. Создай мы по
такому перемещение, закрыть его нечем: `get_cancelled_orders` у WB считает
отменой только `supplierStatus=cancel` (отмена ПРОДАВЦА), и покупательский
отказ из архива обратно не придёт — единица навсегда осталась бы на складе
«Ожидает». Спрашиваем у КЛИЕНТА (`is_cancelled_status`), а не повторяем набор
статусов у себя: тем же набором он узнаёт отмену, и разойдись они, один
механизм считал бы заказ живым, а второй отменённым. Ничего про такой заказ не
записываем: `ProcessedOrder` значит «мы по этому заказу действовали», а здесь
действовать нечего, и строка-пустышка на каждую отмену копилась бы навсегда
(срока хранения у заказов нет). Цена — проверять их каждые сутки заново, а это
сравнение в памяти по уже скачанной ленте, то есть бесплатно.

Потолок на прогон (`MAX_PER_ACCOUNT`) — про ПЕРВЫЙ запуск. Сколько заказов
живой опрос потерял за всё время, мы не знаем: это и есть то, что сверка
выясняет, а узнать объём заранее нечем. Проводим не больше потолка за кабинет
за прогон и ОСТАТОК НАЗЫВАЕМ: молчаливая обрезка здесь — худшее из поведений,
она читается как «всё догнали». Сходится это за несколько суток само.
"""
from __future__ import annotations

import logging
from datetime import timedelta

from sqlalchemy.orm import Session

from app.models import PlatformAccount, ProcessedOrder
from app.timeutils import today_local

logger = logging.getLogger("sync_worker")

# Насколько глубоко спрашиваем ленту. Тридцать суток, а не девяносто (предел
# WB), И НЕ БОЛЬШЕ — по двум причинам сразу. Глубже лежит история, которой мы
# заведомо не управляли: пары тогда либо не были отмечены (и тогда сверка их
# справедливо пропустит), либо были, но переход только начинался, — и первый
# прогон поднял бы её целиком. И `order_poller.OPEN_ORDER_WINDOW_DAYS` тоже
# тридцать: заказ, проведённый сверкой, обязан попасть в окно открытых, иначе
# ни подтверждение, ни отмена по нему отслеживаться не будут вовсе.
AUDIT_WINDOW_DAYS = 30

# Сколько заказов проводим за один прогон на кабинет. См. докстроку: потолок
# про первый запуск, а в обычной работе он не достигается — живой опрос теряет
# единицы, а не десятки.
MAX_PER_ACCOUNT = 50

# Имя источника в `ProcessedOrder.found_by`. Живёт ЗДЕСЬ, у писателя: находка
# отчёта отбирает строки ровно по нему, и повтори она литерал у себя, достаточно
# было бы переименовать источник, чтобы находка замолчала навсегда, не сказав об
# этом ни слова. Тот же урок, что с `retention.BACKLOG_MARK`.
FOUND_BY_AUDIT = "audit"


def _already_known(db: Session, account_id: int, order_ids: list[str]) -> set[str]:
    """Заказы кабинета, про которые у нас уже есть строка — В ЛЮБОМ статусе.

    Любом, а не только `processed`: отменённый и подтверждённый заказ — это
    тоже «мы про него знаем», и спрашивать про них нечего. Одним запросом по
    пачке, а не по заказу: лента за месяц на боевом кабинете — это тысячи
    строк, и подзапрос на каждую означал бы тысячи обращений к базе, в которую
    в это же время пишут рассылка и приём заказов.
    """
    known: set[str] = set()
    # Предел параметров SQLite (999 у сборок до 3.32, чего на машине разработки
    # не увидеть) — то же правило, что у `products.UIDS_CHUNK`.
    chunk = 500
    for start in range(0, len(order_ids), chunk):
        part = order_ids[start:start + chunk]
        known.update(row[0] for row in db.query(ProcessedOrder.order_id).filter(
            ProcessedOrder.account_id == account_id,
            ProcessedOrder.order_id.in_(part),
        ).all())
    return known


def plan_account(db: Session, client, account: PlatformAccount) -> tuple[list, dict]:
    """ОТБОР: какие заказы кабинета сверка считает потерянными. Ничего не меняет.

    Вынесено из `audit_account` по той же причине, по которой в
    `restore_offsets_from_backup` вынесен `plan_restore`: цена ошибки здесь вся
    в отборе — лишний заказ создаст в 1С документ, которого быть не должно,
    недостающий оставит остаток завышенным, и обе ошибки молчаливые. Отдельной
    функцией её можно и закрыть тестами, и ПОКАЗАТЬ человеку до того, как
    что-либо уедет (`scripts/probe_order_audit.py`): сколько заказов опрос
    потерял за всё время, заранее не знает никто.

    Потолок здесь НЕ применяется намеренно — он про проведённые, а не про
    отобранные, и живёт в `audit_account`. Считай мы его здесь, его съедали бы
    заказы по неотмеченным парам (пока идёт переход, их большинство), и до
    настоящих потерь дело не дошло бы никогда.
    """
    stats = {"seen": 0, "known": 0, "cancelled": 0, "problems": []}

    since = today_local() - timedelta(days=AUDIT_WINDOW_DAYS)

    # Лента помнит не всю историю, и слишком старый запрос не падает, а честно
    # отвечает пустотой. Поле есть только там, где предел ПОДТВЕРЖДЁН (WB —
    # спекой и замером); нет поля — нет и проверки, выдумывать предел за
    # площадку мы не станем.
    horizon = getattr(client, "orders_history_days", None)
    if horizon and AUDIT_WINDOW_DAYS > horizon:
        stats["problems"].append(
            f"окно сверки {AUDIT_WINDOW_DAYS} суток глубже, чем лента площадки "
            f"хранит ({horizon}) — часть периода ответит пустотой")

    orders = client.get_orders_since(since)
    lost = getattr(client, "last_unresolved", 0) or 0
    truncated = bool(getattr(client, "last_truncated", False))

    # Неполнота ленты скрывает ЕЩЁ пропуски, но не создаёт ложных: заказ,
    # который в ленте есть, а у нас нет, потерян независимо от того, оборвалась
    # ли выдача дальше. Поэтому найденное проводим, а о неполноте говорим —
    # отказаться значило бы оставить известный оверселл неисправленным из-за
    # того, что мы не знаем про остальные.
    if truncated:
        stats["problems"].append(
            "лента заказов оборвалась на защитном пределе страниц — часть "
            "периода не просмотрена, пропуски в ней остались незамеченными")
    if lost:
        stats["problems"].append(
            f"не удалось получить баркод по {lost} строкам заказов (лимит "
            f"запросов площадки) — эти заказы сверка не видела")

    unique, seen = [], set()
    for o in orders:
        if not o.order_id or o.order_id in seen:
            continue
        seen.add(o.order_id)
        unique.append(o)
    stats["seen"] = len(unique)

    known = _already_known(db, account.id, [o.order_id for o in unique])

    candidates = []
    for o in unique:
        if o.order_id in known:
            stats["known"] += 1
            continue
        # Отменённый на площадке проводить нечего — см. докстроку модуля.
        if client.is_cancelled_status(o.raw_status):
            stats["cancelled"] += 1
            continue
        candidates.append(o)
    return candidates, stats


def audit_account(db: Session, client, account: PlatformAccount,
                  pending_warehouse) -> dict:
    """Сверить ленту одного кабинета и ПРОВЕСТИ найденное.

    Возвращает счётчики. `missed` — проведённые сверкой, то есть ровно те
    продажи, которые живой опрос потерял.
    """
    from app.workers.order_poller import process_new_order
    from app.workers.platform_clients.base import PlatformOrder

    candidates, planned = plan_account(db, client, account)
    stats = {"seen": planned["seen"], "missed": 0,
             "cancelled": planned["cancelled"], "disabled": 0,
             "unmatched": 0, "failed": 0, "left": 0,
             "problems": list(planned["problems"])}

    for o in candidates:
        if stats["missed"] >= MAX_PER_ACCOUNT:
            stats["left"] += 1
            continue

        order = PlatformOrder(order_id=o.order_id, barcode=o.barcode,
                              quantity=o.quantity, raw_status=o.raw_status,
                              order_date=o.order_date)
        try:
            result = process_new_order(
                db, order, account, pending_warehouse(account.platform),
                is_test=False, order_date=o.order_date, respect_enabled=True,
                found_by=FOUND_BY_AUDIT)
            db.commit()
        except Exception as e:                  # noqa: BLE001 — причина уходит текстом
            # По одному заказу, как и в живом опросе: без отката сессия
            # остаётся сломанной после неудачного коммита внутри
            # `process_new_order`, и следующий заказ падал бы на ровном месте.
            # Часть заказов к этому моменту уже проведена — бросать прогон
            # нельзя.
            db.rollback()
            stats["failed"] += 1
            stats["problems"].append(f"заказ {o.order_id}: {type(e).__name__}: {e}")
            continue

        status = result["status"]
        if status == "processed":
            stats["missed"] += 1
            logger.warning(
                "сверка заказов: кабинет «%s», заказ %s от %s не был проведён "
                "живым опросом — проведён сейчас, остаток уменьшен",
                account.name, o.order_id, o.order_date)
        elif status == "skipped_disabled":
            # Пара не отмечена: этой карточкой мы не управляем, остаток по ней
            # наружу не уходил, и продажа мимо нас — норма перехода, а не
            # расхождение. Считаем, чтобы было видно масштаб, но проблемой НЕ
            # объявляем: находка, срабатывающая на норме, приучает пролистывать
            # отчёт целиком.
            stats["disabled"] += 1
        elif status == "unmatched":
            # Баркод не сопоставлен — конфликт сопоставления `process_new_order`
            # уже записал, у него свой читатель в отчёте.
            stats["unmatched"] += 1
        else:
            stats["failed"] += 1

    return stats


def audit_all(db: Session, build_client, accounts: list[PlatformAccount],
              pending_warehouse) -> dict:
    """Пройти по кабинетам. Сбой одного не уносит остальные: площадки
    независимы, и молчание WB — не повод не сверить Kit."""
    total = {"seen": 0, "missed": 0, "cancelled": 0, "disabled": 0,
             "unmatched": 0, "failed": 0, "left": 0, "errors": 0,
             "problems": []}
    for account in accounts:
        try:
            client = build_client(db, account.id)
            stats = audit_account(db, client, account, pending_warehouse)
        except Exception as e:                   # noqa: BLE001 — см. docstring
            # Откат обязателен по той же причине, что в сверке остатков:
            # `audit_account` коммитит, а упавший коммит деактивирует сессию —
            # без отката каждый следующий кабинет падал бы здесь же с
            # `PendingRollbackError`, то есть один сбойный кабинет уносил бы
            # сверку по ВСЕМ.
            db.rollback()
            total["errors"] += 1
            total["problems"].append(
                f"{account.name}: {type(e).__name__}: {e}")
            logger.warning("сверка заказов, кабинет «%s»: %s: %s",
                           account.name, type(e).__name__, e)
            continue
        for key, value in stats.items():
            if key == "problems":
                total["problems"] += [f"{account.name}: {p}" for p in value]
            else:
                total[key] += value
    return total

"""Code128 (набор B) в инлайновый SVG. Без зависимостей.

Зачем своё. Наклейку печатает браузер складской машины, а рисует её сервер —
значит штрихкод должен уехать прямо в разметке, без картинок и без шрифта:
шрифт надо ставить на каждую машину, картинка — это ещё один запрос, который
может не успеть до печати. Восемьдесят строк кодировщика дешевле и проверяются
тестом на известных значениях.

Набор B (печатные ASCII) выбран потому, что номер выглядит как `RET-1284`:
буквы и дефис. Набор C вдвое плотнее, но только для цифр, а цифробуквенный
номер человек читает глазами — это половина смысла наклейки.
"""

from __future__ import annotations

# Стандартная таблица Code128: 107 шаблонов, каждый — ширины полос и пробелов,
# начиная с полосы. Последний (стоп) на один элемент длиннее.
PATTERNS = (
    "212222", "222122", "222221", "121223", "121322", "131222", "122213", "122312",
    "132212", "221213", "221312", "231212", "112232", "122132", "122231", "113222",
    "123122", "123221", "223211", "221132", "221231", "213212", "223112", "312131",
    "311222", "321122", "321221", "312212", "322112", "322211", "212123", "212321",
    "232121", "111323", "131123", "131321", "112313", "132113", "132311", "211313",
    "231113", "231311", "112133", "112331", "132131", "113123", "113321", "133121",
    "313121", "211331", "231131", "213113", "213311", "213131", "311123", "311321",
    "331121", "312113", "312311", "332111", "314111", "221411", "431111", "111224",
    "111422", "121124", "121421", "141122", "141221", "112214", "112412", "122114",
    "122411", "142112", "142211", "241211", "221114", "413111", "241112", "134111",
    "111242", "121142", "121241", "114212", "124112", "124211", "411212", "421112",
    "421211", "212141", "214121", "412121", "111143", "111341", "131141", "114113",
    "114311", "411113", "411311", "113141", "114131", "311141", "411131", "211412",
    "211214", "211232", "2331112",
)

START_B = 104
STOP = 106


class BarcodeError(ValueError):
    """Символ, который набором B не закодировать."""


def values(text: str) -> list[int]:
    """Номера символов Code128 B плюс старт и контрольная сумма.

    Контрольная сумма — взвешенная: стартовый код с весом 1, дальше позиция
    начиная с единицы. Ошибка здесь не видна глазами вовсе: штрихкод
    напечатается и не прочитается, а понять это можно только сканером — поэтому
    она закрыта тестом на известных значениях.
    """
    codes = [START_B]
    for ch in text:
        n = ord(ch)
        if not 32 <= n <= 127:
            raise BarcodeError(f"символ {ch!r} не кодируется набором B")
        codes.append(n - 32)
    checksum = codes[0]
    for i, code in enumerate(codes[1:], start=1):
        checksum += i * code
    codes.append(checksum % 103)
    codes.append(STOP)
    return codes


def svg(text: str, width_mm: float = 46.0, height_mm: float = 12.0) -> str:
    """Готовый `<svg>` со штрихкодом. Ширина модуля считается от ширины поля.

    `shape-rendering="crispEdges"` обязателен: без него браузер сглаживает края
    полос, и на 203 dpi термопринтера узкая полоса превращается в серую — такой
    код сканер берёт через раз.
    """
    codes = values(text)
    widths = []
    for code in codes:
        widths.extend(int(c) for c in PATTERNS[code])
    total = sum(widths)

    module = width_mm / total
    bars = []
    x = 0.0
    for i, w in enumerate(widths):
        if i % 2 == 0:          # чётные элементы — полосы, нечётные — пробелы
            bars.append(f'<rect x="{x:.4f}" y="0" width="{w * module:.4f}" '
                        f'height="{height_mm}" fill="#000"/>')
        x += w * module
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width_mm}mm" '
            f'height="{height_mm}mm" viewBox="0 0 {width_mm} {height_mm}" '
            f'shape-rendering="crispEdges" role="img" '
            f'aria-label="Штрихкод {text}">' + "".join(bars) + "</svg>")

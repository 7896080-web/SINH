"""Проверка функционала обработки 1С обязана КРИЧАТЬ, а не соглашаться.

Обработку правят в Конфигураторе, и правки бывают не наши. Отказ при этом
немой: обмен продолжает работать, просто перестаёт делать что-то одно — не
публикует файл, не называет команду в ответе, не ищет проведённый документ
перед повтором. Узнать об этом можно было бы только по следствию, то есть
неделями позже и уже на остатках.

Поэтому тесты здесь не про «скрипт запускается», а про то, что КАЖДАЯ потеря
ловится: на боевом модуле всё зелено, а стоит убрать возможность — скрипт
называет её и выходит ненулевым кодом. Проверка, которая молчит на сломанном
входе, неотличима от проверки, которой нечего сказать.

Прогоняем САМ СКРИПТ подпроцессом: предмет правки — то, что увидит человек в
консоли сервера после того, как ему принесли доработанную `.epf`.
"""
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "check_1c_module.py"
LIVE = ROOT / "1c" / "ОбменССайтом_МодульОбъекта.txt"


def _run(path) -> tuple[int, str]:
    done = subprocess.run([sys.executable, str(SCRIPT), str(path)],
                          capture_output=True, text=True, cwd=str(ROOT))
    return done.returncode, done.stdout + done.stderr


def _broken(tmp_path, old: str, new: str = "") -> Path:
    """Копия боевого модуля с вынутой возможностью."""
    text = LIVE.read_text(encoding="utf-8-sig")
    assert old in text, f"в модуле нет {old!r} — тест стерёг бы пустоту"
    path = tmp_path / "module.txt"
    path.write_text(text.replace(old, new), encoding="utf-8")
    return path


def test_the_live_module_passes_everything():
    """Молчание на исправном входе — обязательное свойство.

    Скрипт, ругающийся на рабочую обработку, человек перестанет запускать
    первым же днём, и тогда он бесполезен весь.
    """
    code, out = _run(LIVE)

    assert code == 0, out
    assert "НЕТ]" not in out
    assert "нужный нам функционал на месте" in out


@pytest.mark.parametrize("old,new,expected", [
    # Своя команда, выброшенная чужой правкой: канал перестаёт работать молча.
    ('ИначеЕсли Команда = "SCRAP_RETURN"', 'ИначеЕсли Команда = "НЕТУ"',
     "обработка не разбирает"),
    # Публикация файла, который мы ждём: приложение будет ждать его вечно.
    ('"delta_"', '"НЕТУ_"', "не публикуется"),
    # Идемпотентность создания — без неё повтор спишет остаток ВТОРОЙ раз.
    ("НайтиПроведённоеПеремещение", "НайтиЧтоНибудь", "идемпотентность создания"),
    # Идемпотентность утилизации: повтор сделал бы вторую пару документов.
    ("НайтиПроведённоеСписаниеВозврата", "НайтиИное", "идемпотентность утилизации"),
    # Реверсы: вторая отмена вернула бы на ЦС вдвое больше, чем оттуда уезжало.
    ("sync REVERSE", "sync ЧТОТО", "реверсы исключены"),
    # Метка ответа из текущего времени: два файла в секунду затрут друг друга.
    ('СтрЗаменить(ФайлЗадания.Имя, "task_", "")', 'Строка(ТекущаяДата())',
     "метка ответа"),
    # Хоз. операция, зашитая в обработке: подмена считалась бы как брак.
    ('ХозОперация = ?(Поля.Количество() > 8, СокрЛП(Поля[8])',
     'ХозОперация = "Утилизация Брака"; Ненужное = ?(Ложь, СокрЛП(Поля[8])',
     "хоз. операция"),
    # Реквизит документа списания, удалённый заодно с соседней строкой.
    ("СтрокаТовара.СтатьяЗатрат =", "СтрокаТовара.НеТо =", "реквизиты списания"),
    # Проверка длины строки до обращения по индексу.
    ("Если Поля.Количество() < 7 Тогда", "Если Ложь Тогда",
     "длина строки до индексации"),
    # Справочник по угаданному имени вместо метаданных.
    ('ОписаниеТипа.СодержитТип(Тип("СправочникСсылка.', 'Ложь И (Тип("Прочее.',
     "справочник по метаданным"),
])
def test_a_lost_capability_is_named(tmp_path, old, new, expected):
    """Каждая потеря названа своим именем, а не общим «что-то не так».

    Общее «проверка не прошла» заставляет искать причину в семистах строках
    модуля; название говорит, что именно перестанет работать.
    """
    code, out = _run(_broken(tmp_path, old, new))

    assert code == 1, out
    assert expected in out, out
    assert "ПОТЕРЯНО ИЛИ ИЗМЕНЕНО" in out


def test_an_unbalanced_block_is_caught(tmp_path):
    """Лишний «КонецЕсли» глазами в семистах строках не заметить.

    Компилятора 1С в нашей среде нет, и это ему замена: Конфигуратор покажет
    ошибку по Ctrl+F7, но только если человек до него дойдёт.
    """
    code, out = _run(_broken(tmp_path, "КонецЕсли;", "КонецЕсли; КонецЕсли;"))

    assert code == 1
    assert "баланс блоков" in out


def test_an_unclosed_transaction_is_caught(tmp_path):
    """Транзакция без отката оставит возврат проведённым, а списание — нет.

    Единица, которой физически нет, вернулась бы в остаток и уехала на
    площадки — ровно тот оверселл, ради которого транзакция и открыта.
    """
    code, out = _run(_broken(tmp_path, "ОтменитьТранзакцию();", ""))

    assert code == 1
    assert "транзакции" in out


def test_without_an_argument_it_says_this_is_not_the_live_epf():
    """Зелёный отчёт по копии из репозитория про живую обработку не говорит
    НИЧЕГО: её правят Конфигуратором, и каталог `1c/` накат не везёт вовсе.

    Без этой оговорки человек прочитал бы «всё на месте» как ответ про бой.
    """
    done = subprocess.run([sys.executable, str(SCRIPT)],
                          capture_output=True, text=True, cwd=str(ROOT))
    out = done.stdout + done.stderr

    assert "это копия из репозитория" in out, out
    assert "Выгрузите модуль Конфигуратором" in out


def test_a_missing_file_is_refused_plainly(tmp_path):
    """Скрипт запускают с консоли сервера, где путь набирают руками."""
    code, out = _run(tmp_path / "нет-такого.txt")

    assert code == 2
    assert "Файла нет" in out

"""Исходник обработки 1С в `1c/src/` обязан совпадать с боевым модулем.

Почему это тест, а не договорённость. `1c/ОбменССайтом_МодульОбъекта.txt` — копия
модуля из ЖИВОЙ `.epf`, сверенная построчно; правки вносятся туда и переносятся на
сервер Конфигуратором. А `1c/src/` — «готовые к сборке исходники», и README даёт
две инструкции, как собрать из них `.epf`.

Аудит 21.09 нашёл их разошедшимися на 274 строки: в `1c/src` не было НИ ОДНОЙ из
трёх правок 19.09 и не было дельты остатка ЦС вовсе. Сборка по README откатила бы
1С на состояние до 19.09 — то есть вернула бы потерю ответов (метка с точностью до
секунды), дубли документов (архивирование в конце процедуры), двойную отмену (реверс
находил сам себя) и, страшнее всего, отсутствие проверки `НайтиПроведённоеПеремещение`
при включённом `MOVEMENT_REPOST_ENABLED`: каждый повтор зависшего задания списал бы
остаток ВТОРОЙ раз.

Расхождение такого рода ничем не проявляется, пока кто-нибудь не пересоберёт
обработку. Поэтому оно закрыто тестом.
"""
import io
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
LIVE = ROOT / "1c" / "ОбменССайтом_МодульОбъекта.txt"
SRC = ROOT / "1c" / "src" / "ОбменССайтом" / "Ext" / "ObjectModule.bsl"

# Эти проверки — про СОГЛАСОВАННОСТЬ ИСХОДНИКОВ, а не про установку. На боевом
# сервере каталог `1c/` лежит в том виде, в каком его принесла первая установка:
# блоки наката его намеренно не везут (копия на диске сервера на работу не
# влияет), а модуль переносится в `.epf` Конфигуратором. Значит после наката
# файлы там ЗАВЕДОМО старые — и тест, который сравнивает их между собой, упал бы
# на каждом прогоне `pytest -q` после обновления, останавливая накат на ровном
# месте.
#
# Признак «мы в репозитории» — каталог `.git`. На боевом сервере git не
# установлен вовсе и файлы приносятся копированием, так что его там нет.
IN_REPOSITORY = (ROOT / ".git").exists()
repository_only = pytest.mark.skipif(
    not IN_REPOSITORY,
    reason="проверка согласованности исходников 1С имеет смысл только в репозитории: "
           "на сервере каталог 1c/ накатом не обновляется",
)


def _lines(path: Path) -> list[str]:
    # newline="" — читаем как есть, потом нормализуем сами: универсальные
    # переводы строк Python молча склеили бы CRLF с CR и сравнение перестало бы
    # что-либо значить. BOM снимаем через utf-8-sig: у .bsl он есть, у .txt нет,
    # и это нормально — сравниваем содержимое, а не байты.
    with io.open(path, encoding="utf-8-sig", newline="") as fh:
        text = fh.read()
    return text.replace("\r\n", "\n").replace("\r", "\n").split("\n")


@repository_only
def test_the_buildable_source_matches_the_live_module():
    live, src = _lines(LIVE), _lines(SRC)
    assert live == src, (
        f"1c/src разошёлся с боевым модулем: строк {len(src)} против {len(live)}. "
        "Собранная из него .epf откатит обработку 1С — перенесите правки в оба файла."
    )


@repository_only
def test_the_live_module_answers_with_the_command_name():
    """Ответ 1С обязан нести имя команды четвёртым полем.

    Без него `apply_result_batch` сопоставляет ответ с САМЫМ СТАРЫМ незакрытым
    заданием по номеру заказа, а по одному заказу бывает и создание, и отмена:
    ответ по отмене закрывал создание, отмена уходила в `timeout` и навсегда
    считалась «в пути» со знаком минус — остаток завышался ровно на количество
    заказа, и это уезжало на площадки.
    """
    text = LIVE.read_text(encoding="utf-8-sig")
    answers = [ln.strip() for ln in text.splitlines()
               if "СтрокиРезультата.Добавить(" in ln]
    assert answers, "в обработке не нашлось ни одной строки ответа"
    for line in answers:
        assert ('+ "|" + Команда' in line
                or '|CANCEL_MOVEMENT"' in line), f"ответ без имени команды: {line}"


@repository_only
def test_the_live_module_checks_field_count_before_indexing():
    """Длина строки задания проверяется ДО обращения к полям.

    Падение на `Поля[5]` роняет разбор файла целиком, а файл задания при этом не
    архивируется (архивирование ниже по процедуре) — следующий запуск разбирает
    его заново. Для `CANCEL_MOVEMENT` это создаёт ЕЩЁ ОДИН обратный документ
    каждую минуту: отмена идемпотентной не сделана и сделана быть не может.
    """
    text = LIVE.read_text(encoding="utf-8-sig")
    assert "Если Поля.Количество() < 7 Тогда" in text
    assert "Если Поля.Количество() < 2 Тогда" in text

"""Резервная копия базы — самостоятельный запуск.

Ту же копию снимает воркер раз в сутки (`scheduler.job_backup`). Этот скрипт
нужен для двух случаев: снять копию прямо сейчас, руками, перед накатом или
рискованной правкой, — и повесить её в планировщик заданий Windows, если не
полагаться на то, что воркер жив.

    C:\\sync_admin\\.venv\\Scripts\\python.exe C:\\sync_admin\\scripts\\backup_db.py

Ничего не останавливает: копия снимается на живой базе штатным механизмом
SQLite и сразу проверяется. Возвращает 0 при успехе и 1 при любой неудаче —
планировщик Windows по этому коду покажет задание упавшим.

`--local-only` — не трогать вторую площадку. Этим ключом зовёт накат: его копия
отвечает на вопрос «чем откатить миграцию через десять минут», то есть нужна
на диске и СРАЗУ, а выгрузка той же копии в облако на медленном канале идёт
десятками минут (замер: WebDAV Яндекса, 111 КиБ/с, 305 МБ — сорок шесть минут)
и предел ей дан в четыре часа. Всё это время накат стоит на шаге «копия базы»,
а на сервере уже лежат НОВЫЕ файлы при работающих СТАРЫХ службах — то самое
состояние, которое накат и должен проходить насквозь. 15.10 на pm160 это и
случилось: «Копия базы перед миграцией...» и тишина.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.backup import (backup_dir, last_backup, make_backup,  # noqa: E402
                        mirror_dir, rclone_settings)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Резервная копия базы.")
    parser.add_argument("--local-only", action="store_true",
                        help="только локальная копия, без второй площадки "
                             "(так зовёт накат: ему нужна копия сразу)")
    # `None` значит «без аргументов», а НЕ `sys.argv`. Умолчание argparse
    # читает командную строку процесса, а этот `main` зовут и в тестах, и из
    # приложения — там в `sys.argv` лежит командная строка pytest, и скрипт
    # падал на «unrecognized arguments». Командную строку передаёт точка входа
    # внизу, и только она.
    args = parser.parse_args([] if argv is None else argv)

    # Говорим ДО долгого шага, а не после. Человек запускает скрипт руками и
    # смотрит в консоль: сорок шесть минут тишины он читает как «повисло» —
    # ровно так и прочитали накат 15.10. Та же беда, что у `RCLONE_TIMEOUT`,
    # только с этой стороны: «медленно» и «повисло» различимы лишь если про
    # «медленно» сказано вслух.
    if not args.local_only and rclone_settings() is not None:
        print("вторая площадка — облако; на медленном канале выгрузка копии "
              "идёт десятками минут, это не зависание")

    result = make_backup(offsite=not args.local_only)
    if not result.ok:
        print(f"БЭКАП НЕ СНЯТ: {result.error}")
        if result.path_kept:
            # Негодный файл оставлен для разбора, но ПОД ДРУГИМ ИМЕНЕМ: под
            # обычным он прошёл бы у `last_backup` и у суточного задания за
            # полноценную копию — и мониторинг был бы зелёным при отсутствующей
            # копии.
            print(f"неудавшаяся копия отложена: {result.path_kept}")
        return 1
    moment, total = last_backup()
    print(f"копия: {result.path}")
    print(f"размер: {result.size_bytes / 1024 / 1024:.1f} МБ")
    print(f"удалено старых: {result.removed}")
    print(f"всего копий в {backup_dir()}: {total}")
    # Про КАЖДУЮ вторую площадку говорим вслух — и когда она есть, и когда её
    # нет. Раньше строка печаталась только у настроенной папки, а про облако не
    # было ни слова: его молчание одинаково значило и «выгрузили», и «выгружать
    # некуда». Различить по выводу было нельзя — тот самый дефект «ненастроенное
    # выглядит как исправное», который в самой программе закрыт везде, а в этом
    # скрипте остался. Человек запускает его именно чтобы УБЕДИТЬСЯ.
    if args.local_only:
        # Молчать тут нельзя: «копия снята» без оговорки читается как «и в
        # облаке тоже», а её там нет. Чья это работа — говорим сразу.
        print("вторая площадка не тронута (--local-only): её копию снимет "
              "суточное задание")
        return 0
    folder = mirror_dir()
    remote = rclone_settings()
    print(f"зеркало (папка): {folder if folder else 'не настроено'}")
    print(f"зеркало (облако): {remote[1] if remote else 'не настроено'}")

    if result.mirror_error:
        # Не возвращаем 1: копия СНЯТА и проверена, и объявлять прогон упавшим
        # из-за недоступной сетевой папки нельзя — планировщик Windows показал бы
        # задание сбойным там, где главное сделано. Но сказать обязаны: вторая
        # площадка заводится против отказа диска, и зеркало, о котором думают,
        # что оно работает, хуже отсутствующего.
        # НЕ «копия не доехала до зеркала»: площадок две, и отказ одной не
        # значит, что не сработала и вторая. Сказав так, мы бы напугали
        # человека там, где копия на самом деле лежит в облаке, — и приучили
        # бы не верить этой строке.
        print(f"ВНИМАНИЕ: со второй площадкой не всё в порядке — {result.mirror_error}")
        survived = [name for name, on, tag in (("папка", folder, "папка:"),
                                               ("облако", remote, "облако:"))
                    if on and tag not in result.mirror_error]
        if survived:
            print(f"при этом доставлено и проверено: {', '.join(survived)}")
    elif folder or remote:
        # Доехало И ПРОВЕРЕНО: у папки это переименование под финальным именем,
        # у облака — чтение списка на той стороне со сверкой размера.
        print("копия доставлена и проверена на второй площадке")
    else:
        print("ВНИМАНИЕ: второй площадки нет — все копии лежат на том же диске, "
              "что и база. Отказ этого диска унесёт разом и её, и все копии.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

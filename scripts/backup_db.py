"""Резервная копия базы — самостоятельный запуск.

Ту же копию снимает воркер раз в сутки (`scheduler.job_backup`). Этот скрипт
нужен для двух случаев: снять копию прямо сейчас, руками, перед накатом или
рискованной правкой, — и повесить её в планировщик заданий Windows, если не
полагаться на то, что воркер жив.

    C:\\sync_admin\\.venv\\Scripts\\python.exe C:\\sync_admin\\scripts\\backup_db.py

Ничего не останавливает: копия снимается на живой базе штатным механизмом
SQLite и сразу проверяется. Возвращает 0 при успехе и 1 при любой неудаче —
планировщик Windows по этому коду покажет задание упавшим.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.backup import (backup_dir, last_backup, make_backup,  # noqa: E402
                        mirror_dir, rclone_settings)


def main() -> int:
    result = make_backup()
    if not result.ok:
        print(f"БЭКАП НЕ СНЯТ: {result.error}")
        if result.path_kept:
            # Негодный файл оставлен для разбора, но ПОД ДРУГИМ ИМЕНЕМ: под
            # обычным он прошёл бы у `last_backup` и у суточного задания за
            # полноценную копию — и мониторинг был бы зелёным при отсутствующей
            # копии.
            print(f"неудавшаяся копия отложена: {result.path_kept}")
        return 1
    moment, total = last_backup()
    print(f"копия: {result.path}")
    print(f"размер: {result.size_bytes / 1024 / 1024:.1f} МБ")
    print(f"удалено старых: {result.removed}")
    print(f"всего копий в {backup_dir()}: {total}")
    # Про КАЖДУЮ вторую площадку говорим вслух — и когда она есть, и когда её
    # нет. Раньше строка печаталась только у настроенной папки, а про облако не
    # было ни слова: его молчание одинаково значило и «выгрузили», и «выгружать
    # некуда». Различить по выводу было нельзя — тот самый дефект «ненастроенное
    # выглядит как исправное», который в самой программе закрыт везде, а в этом
    # скрипте остался. Человек запускает его именно чтобы УБЕДИТЬСЯ.
    folder = mirror_dir()
    remote = rclone_settings()
    print(f"зеркало (папка): {folder if folder else 'не настроено'}")
    print(f"зеркало (облако): {remote[1] if remote else 'не настроено'}")

    if result.mirror_error:
        # Не возвращаем 1: копия СНЯТА и проверена, и объявлять прогон упавшим
        # из-за недоступной сетевой папки нельзя — планировщик Windows показал бы
        # задание сбойным там, где главное сделано. Но сказать обязаны: вторая
        # площадка заводится против отказа диска, и зеркало, о котором думают,
        # что оно работает, хуже отсутствующего.
        print(f"ВНИМАНИЕ: копия не доехала до зеркала — {result.mirror_error}")
    elif folder or remote:
        # Доехало И ПРОВЕРЕНО: у папки это переименование под финальным именем,
        # у облака — чтение списка на той стороне со сверкой размера.
        print("копия доставлена и проверена на второй площадке")
    else:
        print("ВНИМАНИЕ: второй площадки нет — все копии лежат на том же диске, "
              "что и база. Отказ этого диска унесёт разом и её, и все копии.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
